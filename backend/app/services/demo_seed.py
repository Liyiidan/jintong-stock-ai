"""Deterministic, local-only demo data for development and screenshots.

The seed is intentionally independent of paid market/LLM providers.  It only
touches the dedicated demo account and rows marked with ``source='demo_seed'``.
"""
from datetime import date, datetime, timedelta
import math

from sqlalchemy.orm import Session

from app.core.security import get_password_hash
from app.models.analysis import Analysis
